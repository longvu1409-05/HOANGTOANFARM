-- 1. BẢNG SẢN PHẨM (products)
create table if not exists public.products (
  id text primary key,
  node_id text not null default '',
  name text not null,
  category text not null default 'Trái cây tươi',
  description text not null default '',
  spec_1 text not null,
  spec_2 text not null,
  unit text not null,
  price_vnd integer not null check (price_vnd >= 0),
  price_label text not null,
  image_file text not null,
  crop_json text,
  stock integer not null default 100 check (stock >= 0),
  is_featured smallint not null default 1,
  is_active smallint not null default 1,
  created_at timestamptz not null default now()
);

-- 2. BẢNG ĐƠN HÀNG (orders)
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_code text not null unique,
  product_id text not null references public.products(id),
  product_name text not null,
  unit_price_vnd integer not null,
  quantity integer not null default 1 check (quantity > 0),
  total_price_vnd bigint not null,
  customer_name text not null,
  customer_phone text not null,
  address text not null default '',
  note text not null default '',
  status text not null default 'pending'
    check (status in ('pending', 'confirmed', 'shipping', 'completed', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 3. BẢNG CHI TIẾT TỪNG MÓN TRONG ĐƠN HÀNG (order_items)
create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id text not null references public.products(id),
  product_name text not null,
  unit_price_vnd integer not null,
  quantity integer not null check (quantity > 0),
  subtotal_vnd bigint not null
);

-- 4. BẢNG EMAIL ĐĂNG KÝ NHẬN TIN (newsletter_subscribers)
create table if not exists public.newsletter_subscribers (
  id bigint generated by default as identity primary key,
  email text not null unique,
  created_at timestamptz not null default now()
);

-- 5. BẢNG ĐÁNH GIÁ KHÁCH HÀNG (reviews)
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  author text not null,
  quote text not null,
  rating smallint not null default 5 check (rating between 1 and 5),
  avatar_file text not null default 'imgEllipse47.png',
  created_at timestamptz not null default now()
);

-- 6. BẢNG BÀI VIẾT KIẾN THỨC LỰA CHỌN (knowledge_articles)
create table if not exists public.knowledge_articles (
  id text primary key,
  title text not null,
  excerpt text not null,
  content text not null,
  image_file text not null,
  is_featured smallint not null default 0,
  created_at timestamptz not null default now()
);

-- 7. BẢNG LIÊN HỆ & TƯ VẤN (contacts)
create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  full_name text not null,
  phone text not null,
  email text not null default '',
  subject text not null default 'Tư vấn đặt hàng',
  message text not null,
  status text not null default 'new' check (status in ('new', 'replied')),
  created_at timestamptz not null default now()
);

-- ============================================================================
-- ĐÁNH CHỈ MỤC (INDEX) CHO KHÓA NGOẠI & CỘT TRA CỨU ĐƠN HÀNG NHANH
-- ============================================================================
create index if not exists orders_product_id_idx on public.orders (product_id);
create index if not exists orders_customer_phone_idx on public.orders (customer_phone);
create index if not exists order_items_order_id_idx on public.order_items (order_id);
create index if not exists order_items_product_id_idx on public.order_items (product_id);

-- ============================================================================
-- BẬT BẢO MẬT DÒNG DỮ LIỆU (ROW LEVEL SECURITY - RLS) & PHÂN QUYỀN CHUẨN
-- - Khách ngoài (anon): chỉ được đọc danh mục công khai (sản phẩm, bài viết, đánh giá)
-- - Mọi thao tác quản trị / đơn hàng đều đi qua Backend giữ khóa SUPABASE_SECRET_KEY
-- ============================================================================
grant usage on schema public to anon, authenticated, service_role;
grant select on public.products, public.reviews, public.knowledge_articles to anon, authenticated;
grant all on all tables in schema public to service_role;
grant all on all sequences in schema public to service_role;

alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.newsletter_subscribers enable row level security;
alter table public.reviews enable row level security;
alter table public.knowledge_articles enable row level security;
alter table public.contacts enable row level security;

drop policy if exists "public_read_active_products" on public.products;
create policy "public_read_active_products"
  on public.products for select
  to anon, authenticated
  using (is_active = 1);

drop policy if exists "public_read_reviews" on public.reviews;
create policy "public_read_reviews"
  on public.reviews for select
  to anon, authenticated
  using (true);

drop policy if exists "public_read_knowledge" on public.knowledge_articles;
create policy "public_read_knowledge"
  on public.knowledge_articles for select
  to anon, authenticated
  using (true);

